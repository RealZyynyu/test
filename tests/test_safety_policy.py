"""Development guardrails: fail CI if early NOVA enables unsafe behavior.

These are source-level invariants only, NOT a security audit, sandbox, or proof
of exploit resistance. A secure release requires real runtime and VM testing.
"""
from pathlib import Path
import re
import unittest

ROOT = Path(__file__).resolve().parents[1]


class TestNativeSafetyDefaults(unittest.TestCase):
    def text(self, path):
        return (ROOT / path).read_text(encoding="utf-8")

    def test_iso_requires_explicit_manual_confirmation(self):
        workflow = self.text(".github/workflows/build-native-iso.yml")
        self.assertIn("workflow_dispatch:", workflow)
        self.assertIn("final_release:", workflow)
        self.assertIn("default: false", workflow)
        self.assertRegex(workflow, r"if:\s*\$\{\{\s*inputs\.final_release == true\s*\}\}")
        self.assertNotRegex(workflow, r"(?m)^\s{2}(push|pull_request|schedule):")

    def test_test_iso_workflow_remains_removed(self):
        # Routine development must stay source-only; test images are not
        # generated by a separate push-triggered workflow.
        self.assertFalse(
            (ROOT / ".github/workflows/test-iso.yml").exists(),
            "the automatic test-ISO workflow must remain removed",
        )

    def test_legacy_disk_driver_is_read_only(self):
        ata = self.text("kernel/ata.h")
        # ATA status/command register (0x1F7) must issue only read or identify.
        commands = re.findall(r"nova_ata_out\s*\(\s*0x1F7\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*\)", ata)
        self.assertGreaterEqual(len(commands), 2)
        self.assertEqual(set(int(c, 0) for c in commands), {0xEC, 0x20})
        self.assertNotRegex(ata, r"(?i)\b(outw|outsw|rep\s+outsw|write_sector|format_disk)\s*\(")
        self.assertIn("nova_ata_read_sector", ata)

    def test_vfs_refuses_disk_mutations(self):
        vfs = self.text("kernel/vfs.h")
        for function in ("nova_vfs_write", "nova_vfs_create", "nova_vfs_remove"):
            self.assertIn(function, vfs)
        # In every mutation function, the volume MUST be RAM: only.
        for start_name, end_name in (
            ("static bool nova_vfs_write(", "static bool nova_vfs_create("),
            ("static bool nova_vfs_create(", "static bool nova_vfs_remove("),
        ):
            section = vfs.split(start_name, 1)[1].split(end_name, 1)[0]
            self.assertIn("vol!=NOVA_VFS_RAM", section)
        remove = vfs.split("static bool nova_vfs_remove(", 1)[1].split("#endif", 1)[0]
        self.assertIn("vol!=NOVA_VFS_RAM", remove)

    def test_programs_remain_non_executable_during_development(self):
        paging = self.text("kernel/paging.h")
        process = self.text("kernel/process_image.h")
        app = self.text("kernel/main.c")
        self.assertIn("OFFLINE", paging)
        self.assertIn("NOT runnable processes", process)
        self.assertIn("nova_user_space_prepare", app)
        self.assertIn("nova_pt_prepare", self.text("kernel/user_space.h"))
        # No x86-64 page-table activation or ring-3 transitions are permitted yet.
        self.assertNotRegex(
            app + paging + process,
            r"(?i)(?:movq?\s+[^;\n]{0,60}(?:%|\\)cr3|"
            r"(?:sysretq|swapgs)\s*[;\n]|"
            r"(?:wrmsr|ltr)\s*[;\n])"
        )

    def test_staged_apps_default_deny_and_never_modify_disk(self):
        caps = self.text("kernel/capabilities.h")
        main = self.text("kernel/main.c")
        self.assertIn("NOVA_CAP_IMPLEMENTED", caps)
        self.assertIn("NOVA_CAP_RAM_READ|NOVA_CAP_RAM_WRITE|NOVA_CAP_DISK_READ", caps)
        self.assertIn("nova_cap_mask_valid(mask)", caps)
        self.assertIn("nova_cap_grant_trusted", caps)
        self.assertIn("vol==NOVA_VFS_RAM?NOVA_CAP_RAM_WRITE:0", caps)
        self.assertIn("f->protected", caps)
        self.assertIn("nova_cap_register(&nova_app_policy,&nova_processes,pid)", main)
        self.assertIn("nova_cap_unregister(&nova_app_policy,pid)", main)
        self.assertNotIn("nova_cap_grant_trusted(", main)
        self.assertNotIn("NOVA_CAP_DISK_WRITE", caps)
        saves = self.text("kernel/app_storage.h")
        self.assertIn("NOVA_CAP_APP_SAVE", caps)
        self.assertIn("nova_cap_check(registry,processes,trusted_pid,NOVA_CAP_APP_SAVE)", saves)
        self.assertIn("nova_save_find", saves)
        self.assertIn("nova_save_unregister", main)
        self.assertIn("nova_save_register", main)
        self.assertIn("nova_broker_dispatch", main)
        self.assertIn("NOVA_BROKER_SAVE_WRITE", self.text("kernel/broker.h"))

    def test_offline_broker_stays_bounded_and_requires_trusted_identity(self):
        broker = self.text("kernel/broker.h")
        buffers = self.text("kernel/user_buffer.h")
        app = self.text("kernel/main.c")
        self.assertIn("#define NOVA_BROKER_MAX_BYTES 64u", broker)
        self.assertIn("#define NOVA_BROKER_PATH_CAP 32u", broker)
        self.assertIn("trusted_pid", broker)
        self.assertIn("nova_cap_path_check", broker)
        self.assertIn("nova_cap_read_file", broker)
        self.assertIn("nova_cap_write_ram", broker)
        self.assertIn("NOVA_BROKER_INVALID_REQUEST", broker)
        self.assertIn("NOVA_USER_BUFFER_MAX", buffers)
        self.assertIn("nova_pt_lookup", buffers)
        self.assertIn("nova_user_span_accessible", app)
        self.assertIn("nova_broker_dispatch", app)
        # No hardware entry or untrusted pointers in the request structure.
        request = broker.split("struct nova_broker_request {", 1)[1].split("};", 1)[0]
        self.assertNotIn("*", request)
        self.assertNotIn("pid", request.lower())
        self.assertNotIn("__asm__", broker)

    def test_game_controls_are_a_nonprivileged_adapter(self):
        controls = self.text("kernel/game_input.h")
        self.assertIn("NOVA_GAME_CONTROLLER", controls)
        self.assertIn("nova_game_scan(", controls)
        self.assertIn("nova_game_set(", controls)
        self.assertNotIn("__asm__", controls)
        self.assertIn("nova_game_scan(&nova_game_keys,key)", self.text("kernel/main.c"))


if __name__ == "__main__":
    unittest.main(verbosity=2)
